/** The anchor each principle's section carries, e.g. #principle-3. */
export function principleAnchor(number: number): string {
  return `principle-${number}`;
}

/** The principle a URL hash points at (#principle-3 → 3), or null for any other hash. */
export function principleFromHash(hash: string): number | null {
  const match = /^#?principle-(\d{1,2})$/.exec(hash);
  if (!match) return null;
  const number = Number(match[1]);
  return number >= 1 && number <= PRINCIPLES.length ? number : null;
}

